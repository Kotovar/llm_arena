/**
 * Лимиты служебных git-шагов. Агент имеет право положить в решение сборку, вендорную копию
 * библиотеки или минифицированный бандл: это не ошибка агента, а обычный вид результата.
 * Поэтому лимиты ограничивают только то, что арена хранит и показывает, и никогда — сам результат.
 */
export const DIFF_LIMITS = {
  /** Патч целиком. Всё, что больше, обрезается: этот файл целиком уходит в <pre> браузера. */
  maxDiffBytes: 2 * 1024 * 1024,
  /** Один файл в патче. Отсекает вендорные копии и бандлы, оставляя рукописный код. */
  maxFileDiffBytes: 256 * 1024,
  /** Тот же порог по строкам: минифицированный бандл бывает мал, генерируемый — длинный. */
  maxFileDiffLines: 4_000,
  /** Буфер служебной команды. Нужен только метаданным (numstat, ls-tree), патч идёт мимо него. */
  maxCommandOutputBytes: 8 * 1024 * 1024,
  /** Сколько вывода упавшей команды попадает в текст ошибки. Остальное остаётся в размере. */
  errorPreviewBytes: 2_000,
  /** Сколько файлов перечисляем в метаданных патча: список едет в result_json и в API. */
  maxSummaryFiles: 100,
  /** Потолок исключающих pathspec в argv: вендорный node_modules упёрся бы в ARG_MAX. */
  maxExcludedPaths: 500,
};

export function formatBytes(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}
